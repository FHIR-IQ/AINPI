"""Role coverage by profession across two releases, from two H54 outputs.

Writes frontend/public/api/v1/role-gap-delta.json. The file had no generator
until 2026-10-13: it was written by hand for the 2026-05-08 -> 2026-08-20 pair.
It is a pure diff of two `role-gap-composition.json` payloads, so it needs no
BigQuery. Run it after h54_role_gap_composition.py has regenerated the current
release, with the outgoing payload vendored under
analysis/release-snapshots/published/:

    python3 analysis/role_gap_delta.py \
        --before analysis/release-snapshots/published/role-gap-composition@<sha>.json

`analysis/measures.py` reads `overall` from this file for role-coverage-pa.
"""

from __future__ import annotations

import argparse
import json
import pathlib
from typing import Optional

ROOT = pathlib.Path(__file__).resolve().parent.parent
AFTER_DEFAULT = ROOT / "frontend/public/api/v1/findings/role-gap-composition.json"
OUT_DEFAULT = ROOT / "frontend/public/api/v1/role-gap-delta.json"


def pct(num: int, den: int) -> Optional[float]:
    """Percent, one decimal; three significant digits below 1% so a near-zero
    category does not round to 0.0 and read as empty."""
    if not den:
        return None
    v = 100.0 * num / den
    return round(v, 3) if v < 1 else round(v, 1)


def points(before: Optional[float], after: Optional[float]) -> Optional[float]:
    if before is None or after is None:
        return None
    d = after - before
    return round(d, 2) if abs(d) < 5 and (before < 1 or after < 1) else round(d, 1)


def multiple(before_with: int, after_with: int) -> Optional[float]:
    """after / before in practitioner counts. None when the before side is zero."""
    return round(after_with / before_with, 1) if before_with else None


def _state_block(doc: dict, state: str) -> dict:
    states = doc.get("states") or {}
    if state not in states:
        raise SystemExit(f"{state} not in the H54 payload for {doc.get('release_date')}")
    return states[state]


def build(before_doc: dict, after_doc: dict, state: str = "PA") -> dict:
    b_rel, a_rel = before_doc.get("release_date"), after_doc.get("release_date")
    if not b_rel or not a_rel:
        raise SystemExit("both H54 payloads must carry release_date")
    if b_rel >= a_rel:
        raise SystemExit(f"--before ({b_rel}) must be an earlier release than the current payload ({a_rel})")
    b, a = _state_block(before_doc, state), _state_block(after_doc, state)

    b_cats = {r["category"]: r for r in b["role_coverage_by_category"]}
    a_cats = {r["category"]: r for r in a["role_coverage_by_category"]}
    rows = []
    for cat in a_cats.keys() | b_cats.keys():
        br, ar = b_cats.get(cat), a_cats.get(cat)
        if br is None or ar is None:
            # A category that crossed H54's minimum size in one release only.
            # Reported by name so nothing disappears silently.
            continue
        bp, ap = pct(br["with_role"], br["total"]), pct(ar["with_role"], ar["total"])
        rows.append({
            "category": cat,
            "before_with_role": br["with_role"], "before_total": br["total"], "before_pct": bp,
            "after_with_role": ar["with_role"], "after_total": ar["total"], "after_pct": ap,
            "points": points(bp, ap),
            "multiple": multiple(br["with_role"], ar["with_role"]),
        })
    rows.sort(key=lambda r: (-(r["after_pct"] or 0), r["category"]))
    unmatched = sorted(a_cats.keys() ^ b_cats.keys())

    out = {
        "from": b_rel,
        "to": a_rel,
        "state": state,
        "note": f"Role coverage by profession, {b_rel} to {a_rel}, from two H54 runs "
                "(role-gap-composition.json). Generated by analysis/role_gap_delta.py.",
        "overall": {
            "before": {"active": b["active_practitioners"], "with_role": b["with_ndh_role"],
                       "pct": pct(b["with_ndh_role"], b["active_practitioners"])},
            "after": {"active": a["active_practitioners"], "with_role": a["with_ndh_role"],
                      "pct": pct(a["with_ndh_role"], a["active_practitioners"])},
        },
        "by_category": rows,
    }
    if unmatched:
        out["categories_in_one_release_only"] = unmatched
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--before", required=True, type=pathlib.Path,
                    help="H54 payload for the earlier release (a vendored copy)")
    ap.add_argument("--after", type=pathlib.Path, default=AFTER_DEFAULT)
    ap.add_argument("--state", default="PA")
    ap.add_argument("--out", type=pathlib.Path, default=OUT_DEFAULT)
    args = ap.parse_args()
    doc = build(json.loads(args.before.read_text()), json.loads(args.after.read_text()), args.state)
    args.out.write_text(json.dumps(doc, indent=2) + "\n")
    o = doc["overall"]
    print(f"{doc['state']} {doc['from']} -> {doc['to']}: "
          f"{o['before']['pct']}% -> {o['after']['pct']}% with a role, {len(doc['by_category'])} categories")


if __name__ == "__main__":
    main()
